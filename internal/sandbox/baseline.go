// Package sandbox builds and launches the bubblewrap sandbox. It runs inside the broker's namespaces
// (see package broker). All mount arguments come from a plan.Plan; this package adds only the
// non-mount hardening flags and the environment.
package sandbox

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/H3mul/isolait/internal/plan"
)

// SystemDirs are exposed read-only. A host symlink (merged /usr layouts: /bin -> usr/bin) is recreated as a
// symlink, a missing one is skipped. Nothing else of the host root is visible.
var SystemDirs = []string{"/usr", "/bin", "/sbin", "/lib", "/lib32", "/lib64", "/libx32"}

// EtcPaths is the minimal /etc: the user database, name-service config, hosts, timezone and the linker
// and TLS trust configuration programs need to start. Resolver config is generated by the network engine.
var EtcPaths = []string{
	"/etc/passwd", "/etc/group", "/etc/nsswitch.conf", "/etc/hosts", "/etc/host.conf", "/etc/localtime",
	"/etc/os-release", "/etc/ld.so.cache", "/etc/ld.so.conf", "/etc/ld.so.conf.d",
	"/etc/ssl", "/etc/ca-certificates", "/etc/pki", "/etc/alternatives",
}

// Spec is everything the baseline needs.
type Spec struct {
	HostHome    string   // the user's home path on the host; the persistent sandbox home is mounted at this path
	AgentHome   string   // host directory holding the persistent per-agent home
	Stage       string   // broker-side stage directory, bound at /workspaces
	AllowUserns bool     // opt in to nested user namespaces
	Env         []string // complete sandbox environment as K=V (see BuildEnv)
	Chdir       string   // initial working directory inside the sandbox
	InitExe     string   // host path of the isolait binary, bound read-only at /isolait/init as the init shim
	InitArgs    []string // arguments after /isolait/init (default: init)
	Bwrap       string   // path to bwrap; empty means look it up on PATH
	ResolvConf  string   // host path of the generated resolver config bound at /etc/resolv.conf; empty means none

	// OnNetns, when set, makes the sandbox wait (bwrap --block-fd) after its namespaces exist and before it sets
	// up its filesystem or runs anything, and is called with the sandbox's PID so the network engine can bring up
	// the interface in its network namespace first. An error aborts the start.
	OnNetns  func(childPID int) error `json:"-"`
	UID, GID int
}

// Workspaces is where the broker mounts workspaces inside the sandbox.
const Workspaces = "/workspaces"

// InitPath is where the isolait binary appears inside the sandbox to run as PID 1; AgentLinkDir holds the
// symlink that lets the agent be started by name.
const (
	InitPath     = "/isolait/init"
	AgentLinkDir = "/isolait/bin"
)

// BuildPlan returns the baseline filesystem plan: read-only system dirs, minimal /etc, /dev, /proc,
// memory-backed /tmp, the persistent per-agent home and the /workspaces stage.
func BuildPlan(s Spec) (*plan.Plan, error) {
	var p plan.Plan
	add := func(e plan.Entry) error { return p.Add(e) }

	for _, d := range SystemDirs {
		fi, err := os.Lstat(d)
		switch {
		case err != nil:
			continue
		case fi.Mode()&os.ModeSymlink != 0:
			target, err := os.Readlink(d)
			if err != nil {
				return nil, err
			}
			if err := add(plan.Entry{Kind: plan.Symlink, Src: target, Dst: d}); err != nil {
				return nil, err
			}
		case fi.IsDir():
			if err := add(plan.Entry{Kind: plan.RoBind, Src: d, Dst: d}); err != nil {
				return nil, err
			}
		}
	}
	for _, f := range EtcPaths {
		if _, err := os.Stat(f); err != nil {
			continue
		}
		src, dst := f, f
		if fi, _ := os.Lstat(f); fi != nil && fi.Mode()&os.ModeSymlink != 0 {
			// bind what the link points at so the sandbox gets content, not a dangling link
			real, err := filepath.EvalSymlinks(f)
			if err != nil {
				continue
			}
			src = real
		}
		if err := add(plan.Entry{Kind: plan.RoBind, Src: src, Dst: dst}); err != nil {
			return nil, err
		}
	}
	for _, e := range []plan.Entry{
		{Kind: plan.Dev, Dst: "/dev"},
		{Kind: plan.Proc, Dst: "/proc"},
		// masked after /proc: the listing of kernel keyrings (the audit's F1; the keyctl calls are denied by seccomp)
		{Kind: plan.RoBind, Src: "/dev/null", Dst: "/proc/keys"},
		{Kind: plan.RoBind, Src: "/dev/null", Dst: "/proc/key-users"},
		{Kind: plan.Tmpfs, Dst: "/tmp"},
		{Kind: plan.Bind, Src: s.AgentHome, Dst: s.HostHome},
		{Kind: plan.Bind, Src: s.Stage, Dst: Workspaces},
		{Kind: plan.Dir, Dst: "/isolait"},
		{Kind: plan.Dir, Dst: AgentLinkDir},
	} {
		if err := add(e); err != nil {
			return nil, err
		}
	}
	if s.InitExe != "" {
		if err := add(plan.Entry{Kind: plan.RoBind, Src: s.InitExe, Dst: InitPath}); err != nil {
			return nil, err
		}
	}
	if s.ResolvConf != "" {
		if err := add(plan.Entry{Kind: plan.RoBind, Src: s.ResolvConf, Dst: "/etc/resolv.conf"}); err != nil {
			return nil, err
		}
	}
	return &p, nil
}

// hardening is every non-mount bwrap flag. --as-pid-1 makes our command PID 1 (the init shim) instead of
// bwrap's built-in reaper, so the shim owns reaping and sandbox lifetime. Nested user namespaces are blocked unless opted in: they give
// unprivileged code full capabilities in a child namespace, which reaches root-only kernel code.
func hardening(s Spec) []string {
	a := []string{
		"--unshare-user", "--unshare-pid", "--unshare-ipc", "--unshare-uts", "--unshare-cgroup-try", "--unshare-net",
		"--uid", fmt.Sprint(s.UID), "--gid", fmt.Sprint(s.GID),
		"--die-with-parent", "--new-session", "--as-pid-1", "--cap-drop", "ALL", "--clearenv",
	}
	if !s.AllowUserns {
		a = append(a, "--disable-userns")
	}
	return a
}

// Args assembles the full bwrap argument list (without the command): hardening, the plan, environment,
// working directory. extra carries fd flags such as --info-fd added by the launcher.
func Args(s Spec, p *plan.Plan, extra ...string) []string {
	a := append([]string{}, hardening(s)...)
	a = append(a, extra...)
	a = append(a, p.Args()...)
	for _, kv := range s.Env {
		k, v := splitEnv(kv)
		a = append(a, "--setenv", k, v)
	}
	if s.Chdir != "" {
		a = append(a, "--chdir", s.Chdir)
	}
	return a
}
